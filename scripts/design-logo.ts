async function pixels(file: string) {
  return sharp(file).toColourspace('srgb').ensureAlpha().raw().toBuffer({ resolveWithObject: true })
}

const notification = await pixels(`${OUT}/notification-icon.png`)
let transparent = 0
let visible = 0
for (let i = 0; i < notification.data.length; i += 4) {
  const alpha = notification.data[i + 3]
  if (alpha === 0) {
    transparent += 1
    continue
  }
  visible += 1
  if (notification.data[i] !== 255 || notification.data[i + 1] !== 255 || notification.data[i + 2] !== 255) {
    throw new Error('The notification mask contains non-white visible pixels')
  }
}
if (transparent === 0 || visible === 0) throw new Error('The notification mask must contain artwork and transparency')

const adaptive = await pixels(`${OUT}/adaptive-foreground.png`)
let radius = 0
for (let y = 0; y < adaptive.info.height; y += 1) {
  for (let x = 0; x < adaptive.info.width; x += 1) {
    if (adaptive.data[(y * adaptive.info.width + x) * 4 + 3] === 0) continue
    radius = Math.max(radius, Math.hypot(x + 0.5 - 512, y + 0.5 - 512))
  }
}
const diameterDp = (radius * 2 * 108) / 1024
if (diameterDp > 66) throw new Error(`Adaptive artwork exceeds the safe circle: ${diameterDp.toFixed(2)} dp`)

const legacy = await pixels(`${OUT}/launcher.png`)
for (let i = 3; i < legacy.data.length; i += 4) {
  if (legacy.data[i] !== 255) throw new Error('The legacy launcher must be fully opaque')
}

function countComponents(data: Buffer, size: number) {
  const remaining = new Set<number>()
  for (let i = 0; i < size * size; i += 1) {
    if (data[i * 4 + 3] >= 128) remaining.add(i)
  }
  let components = 0
  for (const seed of remaining) {
    const pending = [seed]
    remaining.delete(seed)
    while (pending.length > 0) {
      const point = pending.pop()
      if (point === undefined) break
      const x = point % size
      const neighbours = [point - size, point + size]
      if (x > 0) neighbours.push(point - 1)
      if (x + 1 < size) neighbours.push(point + 1)
      for (const neighbour of neighbours) {
        if (remaining.delete(neighbour)) pending.push(neighbour)
      }
    }
    components += 1
  }
  return components
}

const sizes = [16, 24, 32, 48, 64]
const smallImages: string[] = []
for (const size of sizes) {
  const png = await sharp(Buffer.from(reversed)).resize(size, size).png().toBuffer()
  const rgba = await sharp(png).toColourspace('srgb').ensureAlpha().raw().toBuffer()
  const components = countComponents(rgba, size)
  if (components !== 3) throw new Error(`The ${size}px mark loses one of its three parts: ${components} components`)
  await writeFile(`${REVIEW}/size-${size}.png`, png)
  smallImages.push(`<image href="data:image/png;base64,${png.toString('base64')}" width="${size}" height="${size}"/>`)
}

function at(x: number, y: number, size: number, content: string) {
  return `<g transform="translate(${x} ${y}) scale(${size / 256})">${content}</g>`
}

function label(x: number, y: number, text: string, size = 18, color = ink) {
  return `<text x="${x}" y="${y}" fill="${color}" font-family="Barlow" font-size="${size}">${text}</text>`
}

