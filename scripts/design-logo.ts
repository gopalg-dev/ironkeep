function mark(color: string, scale = 1) {
  const offset = 128 * (1 - scale)
  return `<g transform="translate(${offset} ${offset}) scale(${scale})"><path fill="${color}" d="${path}"/></g>`
}

for (const board of ['SetupStart', 'DarkSetupStart']) {
  const file = `docs/design/canvas-source/${board}.dc.html`
  const html = await readFile(file, 'utf8')
  const logo = /<svg[^>]*aria-label="IronKeep mark"[^>]*>.*?<\/svg>/
  if (!logo.test(html)) throw new Error(`Missing IronKeep mark in ${file}`)
  await writeFile(
    file,
    html.replace(
      logo,
      `<svg width="72" height="72" viewBox="0 0 72 72" role="img" aria-label="IronKeep mark"><rect x="6" y="6" width="60" height="60" rx="18" fill="var(--fg)"/><path d="${path}" transform="translate(12.6 12.6) scale(0.1828125)" fill="var(--bg)"/></svg>`,
    ),
  )
}

function svg(content: string, title: string, width = 256, height = width) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img"><title>${title}</title>${content}</svg>`
}

async function exportPng(name: string, artwork: string, size: number) {
  await sharp(Buffer.from(artwork)).resize(size, size).png().toFile(`${OUT}/${name}.png`)
}

