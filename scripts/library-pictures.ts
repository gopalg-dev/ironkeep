/**
 * Fetches the exercise pictures the web app loads from the free-exercise-db (public domain) and
 * bundles them as small WebP files, two per exercise (start and end of the movement), then writes
 * `src/lib/library-images.ts`, the static map the app requires them through. Idempotent: a picture
 * already on disk is not fetched again. Run after a library change: `bun scripts/library-pictures.ts`.
 */
import { existsSync, mkdirSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import sharp from 'sharp'

import library from '../src/lib/library.json'

const SOURCE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/'
const OUT_DIR = 'assets/library'
const MAP_PATH = 'src/lib/library-images.ts'
/** Wide enough for the library's detail picture on a phone; the list shows a thumbnail of it. */
const WIDTH = 400
const QUALITY = 72

interface Entry {
  id: string
  images?: string[]
}

mkdirSync(OUT_DIR, { recursive: true })

const entries = (library as Entry[]).filter((e) => e.images && e.images.length > 0)
let fetched = 0
for (const entry of entries) {
  for (const [frame, path] of (entry.images ?? []).entries()) {
    const file = join(OUT_DIR, `${entry.id}-${frame}.webp`)
    if (existsSync(file)) continue
    const response = await fetch(SOURCE + path)
    if (!response.ok) throw new Error(`${response.status} for ${path}`)
    const input = Buffer.from(await response.arrayBuffer())
    await sharp(input).resize({ width: WIDTH, withoutEnlargement: true }).webp({ quality: QUALITY }).toFile(file)
    fetched += 1
  }
}

const lines = entries.flatMap((entry) =>
  (entry.images ?? []).map(
    (_path, frame) => `  '${entry.id}-${frame}': require('../../assets/library/${entry.id}-${frame}.webp'),`,
  ),
)
const map = `// Generated by scripts/library-pictures.ts. Do not edit; rerun the script after a library change.
import type { ImageSourcePropType } from 'react-native'

/** Every bundled exercise picture, keyed by \`<exercise id>-<frame>\`; frame 0 is the start, 1 the end. */
export const LIBRARY_IMAGES: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
}
`
await Bun.write(MAP_PATH, map)

const total = readdirSync(OUT_DIR).reduce((sum, name) => sum + statSync(join(OUT_DIR, name)).size, 0)
console.log(`${fetched} pictures fetched, ${lines.length} in the map, ${(total / 1024 / 1024).toFixed(2)} MB on disk`)
